"""GitHub Copilot adapter: custom agent profiles in ``.github/agents/``.

Format, from GitHub's "Custom agents configuration" reference: a Markdown
file named ``<id>.agent.md`` whose YAML frontmatter holds ``name``,
``description`` (required) and ``tools``, followed by the prompt (at most
30,000 characters). ``tools`` takes tool aliases, case-insensitive; an
omitted ``tools`` grants every tool and ``[]`` grants none. Copilot has no
deny list, so denials become a narrower allowlist.

Copilot does not enforce write scopes or worktrees, so those boundaries are
appended to the prompt as instructions and labelled as unenforced.
"""

import json
from typing import List, Optional, Sequence, Tuple

from .roles import DELEGATION_TOOL, Role, split_tool
from .text import code_list, yaml_scalar

AGENTS_DIR = ".github/agents"
MAX_PROMPT_CHARS = 30000

# Primary alias -> the Claude Code tool names GitHub lists as compatible.
ALIASES: Tuple[Tuple[str, Tuple[str, ...]], ...] = (
    ("execute", ("Bash", "PowerShell")),
    ("read", ("Read", "NotebookRead")),
    ("edit", ("Edit", "MultiEdit", "Write", "NotebookEdit")),
    ("search", ("Grep", "Glob")),
    ("agent", ("Agent", "Task")),
    ("web", ("WebSearch", "WebFetch")),
    ("todo", ("TodoWrite",)),
)


class CopilotError(ValueError):
    pass


def _base(tool: str) -> str:
    return split_tool(tool)[0]


def _mcp_alias(tool: str) -> Optional[str]:
    """``mcp__server__tool`` -> ``server/tool``; ``mcp__server`` -> ``server/*``."""
    if not tool.startswith("mcp__") or tool == "mcp__*":
        return None
    parts = tool[len("mcp__"):].split("__", 1)
    server = parts[0]
    name = parts[1] if len(parts) == 2 else "*"
    return "%s/%s" % (server, name)


def map_tools(role: Role) -> Tuple[Optional[List[str]], List[str]]:
    """Return (copilot tools or None for "all tools", tools with no Copilot equivalent).

    Copilot aliases are coarser than Claude Code tools (``edit`` covers Write,
    Edit and NotebookEdit), so the mapping is lossy in a fixed way:

    * A role with an explicit allowlist gets each alias that covers one of its
      allowed tools. Its denials only remove tools that the allowlist already
      leaves out, so they do not change the mapping.
    * A role that inherits every tool gets each alias none of whose tools it
      denies. Denying Bash alone therefore removes the whole shell alias.

    A tool with a specifier other than ``Agent(...)``, such as ``Bash(git *)``,
    is not granted, because its alias would grant the whole tool.
    """
    if role.allowed_tools is None and not role.disallowed_tools:
        return None, []

    granted: List[str] = []
    allowed: List[str] = []
    if role.allowed_tools is None:
        denied = {_base(tool) for tool in role.disallowed_tools}
        for alias, names in ALIASES:
            if not any(name in denied for name in names):
                granted.append(alias)
    else:
        allowed = list(role.allowed_tools)
        allowed_bases = set()
        for tool in allowed:
            name, spec = split_tool(tool)
            if spec is None or name == DELEGATION_TOOL:
                allowed_bases.add(name)
        for alias, names in ALIASES:
            if any(name in allowed_bases for name in names):
                granted.append(alias)

    unmapped: List[str] = []
    known = {name for _, names in ALIASES for name in names}
    for tool in allowed:
        name, spec = split_tool(tool)
        if tool.startswith("mcp__"):
            mcp = _mcp_alias(tool)
            if mcp:
                granted.append(mcp)
            else:
                unmapped.append(tool)
        elif name not in known or (spec is not None and name != DELEGATION_TOOL):
            unmapped.append(tool)
    return granted, unmapped


def unenforced_notes(role: Role, unmapped: Sequence[str]) -> List[str]:
    notes: List[str] = []
    if role.write_paths is not None:
        scope = code_list(role.write_paths) or "nothing"
        notes.append("Write only to %s. Ask the owner before changing any other file." % scope)
    if role.isolation == "worktree":
        notes.append("Make changes on an isolated branch or worktree, never on the default branch.")
    if unmapped:
        notes.append("Not available in this harness: %s." % ", ".join(unmapped))
    return notes


def render_agent(role: Role) -> str:
    tools, unmapped = map_tools(role)
    lines = [
        "---",
        "# Generated by adapters/generate.py from roles/%s/. Edit the role source, then regenerate."
        % role.id,
        "name: %s" % role.id,
        "description: %s" % yaml_scalar(role.description),
    ]
    if tools is not None:
        lines.append("tools: %s" % json.dumps(tools))
    lines.append("---")
    body = role.body
    notes = unenforced_notes(role, unmapped)
    if notes:
        body += (
            "\n## Boundaries in this harness\n\n"
            "Copilot does not enforce these limits, which the Claude Code plugin enforces with "
            "hooks and worktrees. Treat them as hard rules.\n\n"
            + "".join("- %s\n" % note for note in notes)
        )
    if len(body) > MAX_PROMPT_CHARS:
        raise CopilotError(
            "%s: the prompt is %d characters; Copilot accepts at most %d"
            % (role.id, len(body), MAX_PROMPT_CHARS)
        )
    return "\n".join(lines) + "\n\n" + body


def add_agents(outputs, roles: Sequence[Role]) -> None:
    for role in sorted(roles, key=lambda r: r.id):
        outputs.add("%s/%s.agent.md" % (AGENTS_DIR, role.id), render_agent(role))
    outputs.own(AGENTS_DIR)
