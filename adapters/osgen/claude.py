"""Claude Code adapter: the engine plugin under ``engine/``.

Formats follow the Claude Code plugin docs (plugins reference, components,
sub-agents, hooks and workflows pages):

* ``.claude-plugin/plugin.json``: name, version, description, author, license.
* ``agents/<role>.md``: ``name``, ``description``, ``tools``,
  ``disallowedTools``, ``model: inherit`` and, where declared,
  ``isolation: worktree``. Plugin agents ignore ``hooks``, ``mcpServers`` and
  ``permissionMode``, so hooks live at plugin level.
* ``settings.json``: ``{"agent": "<main role>"}``, the only key besides
  ``subagentStatusLine`` that a plugin's settings honor.
* ``hooks/hooks.json``: exec-form command hooks (``command`` plus ``args``),
  which the hooks reference recommends for path placeholders.
"""

import os
from typing import Dict, List, Optional, Sequence

from . import (
    ENGINE_DIR,
    MARKETPLACE_NAME,
    OWNER_NAME,
    PLUGIN_DESCRIPTION,
    PLUGIN_KEYWORDS,
    PLUGIN_LICENSE,
    PLUGIN_NAME,
    PLUGIN_VERSION,
)
from .docs import ordered, role_table
from .outputs import OutputSet
from .roles import DELEGATION_TOOL, Role, main_role, split_tool
from .text import json_text, read_template, render, template_path, yaml_scalar

TOOLS = ("os_config.py", "ledger.py", "protect_paths.py", "protect_shell.py", "protect_team.py", "session_open.py", "session_close_gate.py", "skill_loop.py", "recall.py")
EXECUTABLE_TOOLS = ("ledger.py", "protect_paths.py", "protect_shell.py", "protect_team.py", "session_open.py", "session_close_gate.py", "skill_loop.py", "recall.py")
STATIC_FILES = (
    "workflows/convergence.js",
    "skills/os-boot/references/os-config.md",
    "skills/wizard/SKILL.md",
    "templates/os.config.json",
    # Copied into a project as memory/<name>.md. The .template suffix keeps the
    # files clear of the leak gate's rule for real session handoff notes.
    "templates/memory/HANDOFF.template.md",
    "templates/memory/lessons.template.md",
)
#: Eval cases for the engine's skills, copied verbatim (claude plugin eval layout).
EVALS_DIR = "evals"
PROTECTED_WRITE_MATCHER = "Write|Edit"
SHELL_MATCHER = "Bash|PowerShell"
DELEGATION_MATCHER = "Agent|Task"
HOOK_TIMEOUTS = {"SessionStart": 30, "UserPromptSubmit": 10, "PreToolUse": 30, "Stop": 600}


def scoped_agent_type(role_id: str) -> str:
    """Claude Code names plugin agents ``<plugin>:<name>``."""
    return "%s:%s" % (PLUGIN_NAME, role_id)


def agent_tools(role: Role) -> Optional[str]:
    """The ``tools`` value, with ``Agent(...)`` targets rewritten to scoped names."""
    if role.allowed_tools is None:
        return None
    entries: List[str] = []
    for tool in role.allowed_tools:
        name, spec = split_tool(tool)
        if name == DELEGATION_TOOL and spec is not None:
            targets = [scoped_agent_type(part.strip()) for part in spec.split(",") if part.strip()]
            entries.append("%s(%s)" % (DELEGATION_TOOL, ", ".join(targets)))
        else:
            entries.append(tool)
    return ", ".join(entries)


def render_agent(role: Role) -> str:
    lines = [
        "---",
        "# Generated by adapters/generate.py from roles/%s/. Edit the role source, then regenerate."
        % role.id,
        "# tier: %s (advisory here: every generated agent inherits the session's model)" % role.tier,
        "name: %s" % role.id,
        "description: %s" % yaml_scalar(role.description),
    ]
    tools = agent_tools(role)
    if tools is not None:
        lines.append("tools: %s" % yaml_scalar(tools))
    if role.disallowed_tools:
        lines.append("disallowedTools: %s" % yaml_scalar(", ".join(role.disallowed_tools)))
    lines.append("model: inherit")
    if role.isolation == "worktree":
        lines.append("isolation: worktree")
    lines.append("---")
    return "\n".join(lines) + "\n\n" + role.body


def render_manifest() -> str:
    return json_text(
        {
            "name": PLUGIN_NAME,
            "version": PLUGIN_VERSION,
            "description": PLUGIN_DESCRIPTION,
            "author": {"name": OWNER_NAME},
            "license": PLUGIN_LICENSE,
            "keywords": list(PLUGIN_KEYWORDS),
        }
    )


def manifest_data() -> Dict[str, object]:
    """The manifest fields the marketplace entry needs."""
    return {"name": PLUGIN_NAME}


def render_settings(roles: Sequence[Role]) -> str:
    return json_text({"agent": main_role(roles).id})


def _hook(script: str, event: str, on_failure: Optional[str] = None, args: Sequence[str] = ()) -> Dict[str, object]:
    hook: Dict[str, object] = {
        "type": "command",
        "command": "python3",
        "args": ["${CLAUDE_PLUGIN_ROOT}/tools/%s" % script] + list(args),
        "timeout": HOOK_TIMEOUTS[event],
    }
    if on_failure:
        hook["onFailure"] = on_failure
    return hook


def render_hooks() -> str:
    return json_text(
        {
            "description": (
                "SOTACOMMAND session ritual: preflight report on session start, protected paths "
                "on Write, Edit and shell commands, no work for helpers the owner turned off, a local ledger of counted events, close gate on stop."
            ),
            "hooks": {
                "SessionStart": [{"hooks": [_hook("session_open.py", "SessionStart")]}],
                "UserPromptSubmit": [{"hooks": [_hook("ledger.py", "UserPromptSubmit", args=("--event", "owner_message"))]}],
                "PreToolUse": [
                    {
                        "matcher": PROTECTED_WRITE_MATCHER,
                        "hooks": [_hook("protect_paths.py", "PreToolUse", on_failure="block")],
                    },
                    {
                        "matcher": SHELL_MATCHER,
                        "hooks": [_hook("protect_shell.py", "PreToolUse", on_failure="block")],
                    },
                    {
                        "matcher": DELEGATION_MATCHER,
                        "hooks": [_hook("protect_team.py", "PreToolUse", on_failure="block")],
                    },
                ],
                "Stop": [{"hooks": [_hook("session_close_gate.py", "Stop")]}],
            },
        }
    )


def render_role_policy(roles: Sequence[Role]) -> str:
    return json_text(
        {
            "$comment": (
                "Generated by adapters/generate.py from the role sources. tools/protect_paths.py "
                "reads write_paths; tools/session_open.py checks roles and routes against agents/ "
                "at boot (BOOT_INVALID on drift). Change the role sources, then regenerate."
            ),
            "plugin": PLUGIN_NAME,
            "main_role": main_role(roles).id,
            "roles": [role.id for role in ordered(roles)],
            "routes": list(main_role(roles).delegates_to()),
            "write_paths": {
                role.id: list(role.write_paths)
                for role in ordered(roles)
                if role.write_paths is not None
            },
        }
    )


def _example_role(roles: Sequence[Role]) -> str:
    main = main_role(roles)
    delegates = main.delegates_to() or tuple(role.id for role in ordered(roles) if not role.main)
    return delegates[0] if delegates else main.id


def render_skill(roles: Sequence[Role]) -> str:
    return render(
        read_template("engine", "skills", "os-boot", "SKILL.md"),
        {
            "MAIN_ROLE": main_role(roles).id,
            "ROLE_TABLE": role_table(roles, "Enforced boundary"),
            "PLUGIN_NAME": PLUGIN_NAME,
            "EXAMPLE_ROLE": _example_role(roles),
        },
    )


def render_readme(roles: Sequence[Role]) -> str:
    return render(
        read_template("engine", "README.md"),
        {
            "PLUGIN_NAME": PLUGIN_NAME,
            "MARKETPLACE_NAME": MARKETPLACE_NAME,
            "MAIN_ROLE": main_role(roles).id,
            "ROLE_TABLE": role_table(roles, "Enforced boundary"),
        },
    )


def eval_files() -> tuple:
    """Every file under the engine template's evals/, as engine-relative paths."""
    root = template_path("engine", EVALS_DIR)
    found = []
    for folder, dirs, files in os.walk(root):
        dirs[:] = sorted(d for d in dirs if not d.startswith((".", "__")))  # no caches, no hidden folders
        for name in sorted(files):
            if name.startswith(".") or name.endswith((".pyc", ".pyo")):
                continue
            found.append(os.path.relpath(os.path.join(folder, name), template_path("engine")).replace(os.sep, "/"))
    return tuple(found)


def add_engine(outputs: OutputSet, roles: Sequence[Role]) -> None:
    """Add every file of the engine plugin to ``outputs``."""
    base = ENGINE_DIR + "/"
    outputs.add(base + ".claude-plugin/plugin.json", render_manifest())
    outputs.add(base + "settings.json", render_settings(roles))
    outputs.add(base + "hooks/hooks.json", render_hooks())
    outputs.add(base + "README.md", render_readme(roles))
    for role in ordered(roles):
        outputs.add(base + "agents/%s.md" % role.id, render_agent(role))
    for name in TOOLS:
        outputs.add(
            base + "tools/" + name,
            read_template("engine", "tools", name),
            executable=name in EXECUTABLE_TOOLS,
        )
    outputs.add(base + "tools/role_policy.json", render_role_policy(roles))
    outputs.add(base + "skills/os-boot/SKILL.md", render_skill(roles))
    for relative in STATIC_FILES + eval_files():
        outputs.add(base + relative, read_template("engine", *relative.split("/")))
    for directory in ("agents", "evals", "hooks", "skills", "tools", "templates", "workflows"):
        outputs.own(base + directory)
