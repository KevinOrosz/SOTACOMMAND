"""``REGISTRY.md`` generation and its drift check.

The registry is generated, never edited by hand. Its rows come from each
skill's ``SKILL.md`` frontmatter and from the newest redacted eval summary
that covers the skill. The output is byte-for-byte deterministic for a given
tree (no generation timestamp), so ``registry --check`` can compare it with
the committed file.
"""

import difflib
import os
from pathlib import Path
from typing import List, NamedTuple, Optional, Sequence, Tuple

from . import summary as summary_mod
from .model import PluginInfo, SkillInfo, load_plugins

REGISTRY_FILENAME = "REGISTRY.md"
DEFAULT_ROOTS = ("packs", "labs")
GENERATOR = "python3 tools/repo/skills/skills.py registry"
CONTRACT_PATH = Path("tools") / "repo" / "skills" / "CONTRACT.md"
COLUMNS = ("Skill", "Pack", "Status", "Min tier", "Roles", "Gate", "Latest score", "Δ", "Runs", "Date")
NO_VALUE = "—"


class RegistryError(Exception):
    """The registry can't be generated, for example because a SKILL.md doesn't parse."""


class Row(NamedTuple):
    skill: str
    pack: str
    status: str
    min_tier: str
    roles: str
    gate: str
    skill_link: str
    evidence: Optional[summary_mod.SkillEvidence]


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _rel_link(target: Path, base_dir: Path) -> str:
    return Path(os.path.relpath(str(target), str(base_dir))).as_posix()


def _row(skill: SkillInfo, base_dir: Path) -> Row:
    if skill.frontmatter is None:
        raise RegistryError(
            "{}: frontmatter doesn't parse ({}); run skills.py lint".format(skill.skill_md, skill.parsed.error)
        )
    return Row(
        skill=skill.name,
        pack=skill.meta("pack") or skill.plugin.dir_name,
        status=skill.meta("status") or "unknown",
        min_tier=skill.meta("min-tier") or NO_VALUE,
        roles=", ".join(r.strip() for r in (skill.meta("roles") or "").split(",") if r.strip()) or NO_VALUE,
        gate=skill.meta("gate") or NO_VALUE,
        skill_link=_rel_link(skill.skill_md, base_dir),
        evidence=summary_mod.latest_evidence(skill.plugin.summaries, skill.folder),
    )


def _format_row(row: Row, base_dir: Path) -> str:
    evidence = row.evidence
    if evidence is None:
        score = delta = runs = date = NO_VALUE
    else:
        score = "{:.2f}".format(evidence.score)
        delta = "{:+.2f}".format(evidence.delta) if evidence.delta is not None else NO_VALUE
        runs = str(evidence.runs)
        date = "[{}]({})".format(evidence.date, _rel_link(evidence.summary_path, base_dir))
        if evidence.partial:
            date += " (partial)"
        elif evidence.ablation == "none":
            date += " (no baseline)"
    cells = (
        "[{}]({})".format(row.skill, row.skill_link),
        row.pack,
        row.status,
        row.min_tier,
        row.roles,
        row.gate,
        score,
        delta,
        runs,
        date,
    )
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def collect_rows(plugins: Sequence[PluginInfo], base_dir: Path) -> List[Row]:
    rows = [_row(skill, base_dir) for plugin in plugins for skill in plugin.skills]
    return sorted(rows, key=lambda r: (r.pack, r.skill))


def render(plugins: Sequence[PluginInfo], base_dir: Path, contract_path: Path) -> str:
    """Render REGISTRY.md for ``plugins``; links are relative to ``base_dir``."""
    rows = collect_rows(plugins, base_dir)
    counts = {status: sum(1 for r in rows if r.status == status) for status in ("stable", "experimental", "retired")}
    lines = [
        "# Skill registry",
        "",
        "<!-- Generated by `{}`. Do not edit by hand: CI runs `registry --check` and fails on any difference. -->".format(GENERATOR),
        "",
        "Every skill in `packs/` and `labs/`, built from its `SKILL.md` frontmatter and the newest redacted eval "
        "summary that covers it.",
        "",
        "- **Latest score** is the with-skill score from `claude plugin eval`, from 0 to 1, averaged over the "
        "skill's eval cases.",
        "- **Δ** is the with-skill score minus the no-skill baseline score from the same run.",
        "- **Runs** counts the runs per case in each arm.",
        "- A skill is `stable` only after a qualifying run: a score of at least {:.2f} and a Δ of at least {:+.2f}, "
        "over at least {} runs on the pinned model. See "
        "[the contract]({}).".format(
            summary_mod.STABLE_MIN_SCORE,
            summary_mod.STABLE_MIN_DELTA,
            summary_mod.STABLE_MIN_RUNS,
            _rel_link(contract_path, base_dir),
        ),
        "",
        "| " + " | ".join(COLUMNS) + " |",
        "|" + "|".join("---" for _ in COLUMNS) + "|",
    ]
    if rows:
        lines.extend(_format_row(row, base_dir) for row in rows)
    else:
        lines.append("| " + " | ".join([NO_VALUE] * len(COLUMNS)) + " |")
    lines.extend(
        [
            "",
            "{} skill(s): {} stable, {} experimental, {} retired.".format(
                len(rows), counts["stable"], counts["experimental"], counts["retired"]
            ),
            "",
        ]
    )
    return "\n".join(lines)


def plugin_roots(repo_root: Path, names: Sequence[str] = DEFAULT_ROOTS) -> List[Path]:
    """The existing plugin roots (``packs/``, ``labs/``) under ``repo_root``."""
    return [repo_root / name for name in names if (repo_root / name).is_dir()]


def generate(repo_root: Path, out_path: Optional[Path] = None) -> Tuple[Path, str]:
    """Return the registry path and the text it should hold."""
    out = out_path or (repo_root / REGISTRY_FILENAME)
    plugins = load_plugins(plugin_roots(repo_root))
    return out, render(plugins, out.parent, repo_root / CONTRACT_PATH)


def diff(current: Optional[str], expected: str, path: Path) -> str:
    """A unified diff from the committed registry to the regenerated one."""
    before = (current or "").splitlines(keepends=True)
    after = expected.splitlines(keepends=True)
    return "".join(
        difflib.unified_diff(before, after, fromfile="{} (committed)".format(path.name), tofile="{} (generated)".format(path.name))
    )
